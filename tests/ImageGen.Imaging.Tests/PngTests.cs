using System.Buffers.Binary;
using ImageGen.Imaging;

namespace ImageGen.Imaging.Tests;

public class PngTests
{
    private readonly Png _png = new();

    /// <summary>Builds a small deterministic RGB gradient for test input.</summary>
    private static byte[] Gradient(int width, int height)
    {
        var rgb = new byte[width * height * 3];
        for (var y = 0; y < height; y++)
        for (var x = 0; x < width; x++)
        {
            var i = (y * width + x) * 3;
            rgb[i] = (byte)(x * 255 / Math.Max(1, width - 1));
            rgb[i + 1] = (byte)(y * 255 / Math.Max(1, height - 1));
            rgb[i + 2] = 128;
        }
        return rgb;
    }

    private string SaveTemp(byte[] rgb, int width, int height)
    {
        var path = Path.Combine(Path.GetTempPath(), $"pngtest-{Guid.NewGuid():N}.png");
        _png.Save(path, rgb, width, height);
        return path;
    }

    [Fact]
    public void Save_WritesPngSignature()
    {
        var path = SaveTemp(Gradient(4, 4), 4, 4);
        try
        {
            var bytes = File.ReadAllBytes(path);
            byte[] signature = [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A];
            Assert.True(bytes.Length > signature.Length);
            Assert.Equal(signature, bytes[..8]);
        }
        finally
        {
            File.Delete(path);
        }
    }

    [Fact]
    public void Save_WritesIhdrWithCorrectDimensions()
    {
        const int width = 7, height = 3;
        var path = SaveTemp(Gradient(width, height), width, height);
        try
        {
            var bytes = File.ReadAllBytes(path);
            // IHDR is the first chunk after the 8-byte signature: 4-byte length,
            // 4-byte "IHDR" type, then width/height as big-endian int32s.
            var ihdrData = bytes.AsSpan(16); // 8 sig + 4 len + 4 type
            Assert.Equal(width, BinaryPrimitives.ReadInt32BigEndian(ihdrData));
            Assert.Equal(height, BinaryPrimitives.ReadInt32BigEndian(ihdrData[4..]));
            Assert.Equal(8, ihdrData[8]);  // bit depth
            Assert.Equal(2, ihdrData[9]);  // color type = truecolor RGB
        }
        finally
        {
            File.Delete(path);
        }
    }

    [Fact]
    public void Save_RejectsBufferOfWrongLength()
    {
        // 4x4 needs 48 bytes; give it 47.
        Assert.Throws<ArgumentException>(() => _png.Save(
            Path.Combine(Path.GetTempPath(), "should-not-exist.png"),
            new byte[47], 4, 4));
    }

    // The strongest correctness test: encode then decode must return the original
    // pixels exactly, across a range of sizes (odd widths exercise stride handling).
    [Theory]
    [InlineData(1, 1)]
    [InlineData(4, 4)]
    [InlineData(7, 3)]     // odd width, non-square
    [InlineData(16, 9)]
    [InlineData(1, 100)]   // single column
    [InlineData(100, 1)]   // single row
    public void Load_RoundTripsSavedImage(int width, int height)
    {
        var original = Gradient(width, height);
        var path = SaveTemp(original, width, height);
        try
        {
            var decoded = _png.Load(path);
            Assert.Equal(width, decoded.Width);
            Assert.Equal(height, decoded.Height);
            Assert.Equal(original, decoded.Pixels);
        }
        finally
        {
            File.Delete(path);
        }
    }

    [Fact]
    public void Load_RejectsNonPng()
    {
        var path = Path.Combine(Path.GetTempPath(), $"notpng-{Guid.NewGuid():N}.png");
        File.WriteAllText(path, "this is not a PNG");
        try
        {
            Assert.Throws<ImageFormatException>(() => _png.Load(path));
        }
        finally
        {
            File.Delete(path);
        }
    }

    [Fact]
    public void Decode_RejectsBadSignature()
    {
        var notPng = new byte[16];
        Assert.Throws<ImageFormatException>(() => _png.Decode(notPng));
    }

    // --- Fixture-based decode tests --------------------------------------------
    //
    // The round-trip tests above only exercise filter type 0, because our own
    // encoder always writes filter 0. These fixtures are external PNGs — one per
    // scanline filter (0-4) for RGB, plus an RGBA file — generated by a standalone
    // Python script and independently verified with Pillow (see
    // Fixtures/README.md). Each carries the same construction-known pixel pattern,
    // so decoding must reproduce it exactly. This is what guards the Sub/Up/Average/
    // Paeth unfilter paths and the RGBA alpha-drop path against regression.

    private static string FixturePath(string name) =>
        Path.Combine(AppContext.BaseDirectory, "Fixtures", name);

    /// <summary>The 8x6 RGB pattern all rgb_filter*.png fixtures encode.</summary>
    private static byte[] ExpectedRgb8x6()
    {
        const int w = 8, h = 6;
        var rgb = new byte[w * h * 3];
        for (var y = 0; y < h; y++)
        for (var x = 0; x < w; x++)
        {
            var i = (y * w + x) * 3;
            rgb[i] = (byte)(x * 32);
            rgb[i + 1] = (byte)(y * 48);
            rgb[i + 2] = (byte)(x * y * 3);
        }
        return rgb;
    }

    [Theory]
    [InlineData("rgb_filter0.png")] // None
    [InlineData("rgb_filter1.png")] // Sub
    [InlineData("rgb_filter2.png")] // Up
    [InlineData("rgb_filter3.png")] // Average
    [InlineData("rgb_filter4.png")] // Paeth
    public void Load_DecodesEachScanlineFilter(string fixture)
    {
        var decoded = _png.Load(FixturePath(fixture));
        Assert.Equal(8, decoded.Width);
        Assert.Equal(6, decoded.Height);
        Assert.Equal(ExpectedRgb8x6(), decoded.Pixels);
    }

    [Fact]
    public void Load_DecodesRgbaByDroppingAlpha()
    {
        const int w = 5, h = 4;
        var expected = new byte[w * h * 3];
        for (var y = 0; y < h; y++)
        for (var x = 0; x < w; x++)
        {
            var i = (y * w + x) * 3;
            expected[i] = (byte)(x * 40);
            expected[i + 1] = (byte)(y * 60);
            expected[i + 2] = 90; // alpha (200) dropped
        }

        var decoded = _png.Load(FixturePath("rgba_filter0.png"));
        Assert.Equal(w, decoded.Width);
        Assert.Equal(h, decoded.Height);
        Assert.Equal(expected, decoded.Pixels);
    }
}
